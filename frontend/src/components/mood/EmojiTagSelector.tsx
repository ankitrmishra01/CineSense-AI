export const EmojiTagSelector: React.FC = () => {
  const { selectedEmojis, toggleEmoji, clearEmojis } = useMoodStore();

  return (
    <div>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '10px' }}>
        <span
          style={{
            fontSize: '11px',
            color: 'var(--color-text-muted)',
            textTransform: 'uppercase',
            letterSpacing: '0.08em',
            fontWeight: 600,
          }}
        >
          Select Moods
        </span>
        {selectedEmojis.length > 0 && (
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
            <span style={{ fontSize: '11px', color: 'var(--color-accent-primary)', fontWeight: 600 }}>
              {selectedEmojis.length} {selectedEmojis.length === 1 ? 'selected' : 'selected'}
            </span>
            <button
              type="button"
              onClick={clearEmojis}
              style={{
                background: 'none',
                border: 'none',
                color: 'var(--color-text-muted)',
                fontSize: '11px',
                cursor: 'pointer',
                padding: '2px 4px',
                textDecoration: 'underline',
              }}
            >
              Clear
            </button>
          </div>
        )}
      </div>

      {/* Mood Chip Carousel with Horizontal Scrolling and Edge Fades */}
      <div className="mood-chips-scroll">
        {EMOTION_TAGS.map((tag) => {
          const selected = selectedEmojis.includes(tag.emoji);
          const moodKey = tag.label.toLowerCase();
          const icon = MOOD_ICONS[moodKey];

          return (
            <button
              key={tag.emoji}
              id={`mood-tag-${moodKey}`}
              type="button"
              onClick={() => toggleEmoji(tag.emoji)}
              className="mood-chip"
              style={{
                backgroundColor: selected ? `var(--mood-${moodKey}-bg, var(--color-chip-active-bg))` : 'var(--color-chip-bg)',
                borderColor: selected ? `var(--mood-${moodKey}-border, var(--color-chip-active-border))` : 'var(--color-chip-border)',
                color: selected ? 'var(--color-text-primary)' : 'var(--color-text-secondary)',
                fontWeight: selected ? 600 : 500,
                minHeight: '44px',
                minWidth: '44px',
                padding: '8px 14px',
                flexShrink: 0,
              }}
            >
              <span style={{ display: 'inline-flex', alignItems: 'center', opacity: selected ? 1 : 0.75 }}>
                {icon}
              </span>
              <span>{tag.label}</span>
              {selected && (
                <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="3" strokeLinecap="round" strokeLinejoin="round" style={{ marginLeft: '2px' }}>
                  <polyline points="20 6 9 17 4 12" />
                </svg>
              )}
            </button>
          );
        })}
      </div>
    </div>
  );
};
